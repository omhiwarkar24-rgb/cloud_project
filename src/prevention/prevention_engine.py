"""
prevention_engine.py - Rule-based Automated Prevention Recommendation Engine.
Converts Security Risk and Predictive Maintenance Failure Risk into actionable, plain-English recommendations.

NOTE: These are recommendations generated by the project's rule engine for demonstration purposes,
not automatic real-world control actions.
"""

import json
import os
from datetime import datetime, timezone


BASE_DIR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_CONFIG_PATH = os.path.join(BASE_DIR, "config", "prevention.json")

# Exhaustive Rule Matrix for all combinations of (security_risk_level, failure_risk_level)
RECOMMENDATION_RULE_MATRIX = {
    ("LOW", "LOW"): "All systems operating normally. Continue standard routine monitoring.",
    ("LOW", "MEDIUM"): "Warning: Increased machine failure risk. Increase sensor monitoring frequency and schedule inspection.",
    ("LOW", "HIGH"): "High machine failure risk. Schedule urgent preventive maintenance.",
    
    ("MEDIUM", "LOW"): "Notice: Minor suspicious network activity detected. Increase security logging frequency.",
    ("MEDIUM", "MEDIUM"): "Caution: Moderate security anomaly and equipment degradation detected. Heighten system surveillance.",
    ("MEDIUM", "HIGH"): "High failure risk accompanied by moderate security activity. Schedule maintenance and review firewall logs.",
    
    ("HIGH", "LOW"): "High cybersecurity risk detected. Review suspicious traffic and consider controlled isolation in the test environment.",
    ("HIGH", "MEDIUM"): "High security risk with moderate machine degradation. Review logs and schedule a controlled diagnostic check.",
    ("HIGH", "HIGH"): "Critical combined risk. Prioritize machine inspection and cybersecurity investigation through approved procedures.",
    
    ("CRITICAL", "LOW"): "Critical cybersecurity threat detected. Investigate and consider controlled isolation in the test environment.",
    ("CRITICAL", "MEDIUM"): "Critical security threat with elevated failure risk. Review evidence and inspect machine health before any controlled action.",
    ("CRITICAL", "HIGH"): "Critical combined risk. Prioritize machine inspection and cybersecurity forensic investigation through approved procedures."
}


def load_prevention_config(config_path=DEFAULT_CONFIG_PATH):
    with open(config_path, "r", encoding="utf-8") as config_file:
        return json.load(config_file)


def _percent(value):
    return "N/A" if value is None else f"{float(value) * 100:.1f}%"


def generate_node_recommendations(node_risk, maintenance_result=None, security_result=None, config=None):
    """Generate evidence-backed advisory recommendations for one high-risk node."""
    settings = config or load_prevention_config()
    if node_risk.get("risk_level") not in ("HIGH", "CRITICAL"):
        return []

    node_id = node_risk.get("node_id", "unknown")
    timestamp = node_risk.get("timestamp") or datetime.now(timezone.utc).isoformat()
    priority = "URGENT" if node_risk.get("risk_level") == "CRITICAL" else "ELEVATED"
    vector = (maintenance_result or {}).get("feature_vector") or {}
    recommendations = []

    def add(problem, evidence, action, reason):
        recommendations.append({
            "node_id": node_id,
            "detected_problem": problem,
            "evidence": evidence,
            "recommended_action": action,
            "priority": priority,
            "timestamp": timestamp,
            "why_generated": reason,
            "advisory_only": True,
            "disclaimer": "Recommendation only. No automatic infrastructure repair or isolation is performed.",
        })

    cpu = vector.get("cpu_utilization")
    if cpu is not None and float(cpu) >= settings["cpu_high_threshold"]:
        add(
            "High CPU utilization",
            f"CPU = {float(cpu):.1f}%",
            "Reduce workload or redistribute intensive tasks.",
            "CPU exceeds the configured high-utilization threshold.",
        )

    memory = vector.get("ram_utilization")
    if memory is not None and float(memory) >= settings["memory_high_threshold"]:
        add(
            "High memory utilization",
            f"RAM = {float(memory):.1f}%",
            "Reduce memory-intensive processes or redistribute workload.",
            "RAM utilization exceeds the configured high-utilization threshold.",
        )

    disk = vector.get("disk_utilization")
    if disk is not None and float(disk) >= settings["disk_high_threshold"]:
        add(
            "High disk utilization",
            f"Disk = {float(disk):.1f}%",
            "Reduce disk-intensive workload and schedule capacity review.",
            "Disk utilization exceeds the configured high-utilization threshold.",
        )

    maintenance_risk = node_risk.get("maintenance_risk")
    if maintenance_risk is not None and float(maintenance_risk) >= settings["health_risk_threshold"]:
        add(
            "Increasing health/failure risk",
            f"Maintenance/health risk = {_percent(maintenance_risk)}",
            "Investigate the node and reduce workload while reviewing health signals.",
            "The live health risk exceeds the configured high-risk threshold.",
        )

    security_risk = node_risk.get("security_risk")
    attack_type = (security_result or {}).get("attack_type")
    if security_risk is not None and float(security_risk) >= settings["security_risk_threshold"]:
        label = f" ({attack_type})" if attack_type else ""
        add(
            f"Security anomaly{label}",
            f"Security risk = {_percent(security_risk)}",
            "Investigate the event and consider controlled isolation in the test environment.",
            "Security risk exceeds the configured anomaly threshold; this is an advisory investigation, not an automatic isolation action.",
        )

    if not recommendations:
        add(
            "Elevated combined node risk",
            f"Overall risk = {node_risk.get('risk_level')} ({_percent(node_risk.get('overall_risk'))})",
            "Investigate the node and review the contributing security and health signals.",
            "The node is high risk, but no individual evidence threshold was available.",
        )
    return recommendations


def get_all_node_recommendations():
    """Build live advisory recommendations from persisted node evidence."""
    from central_server.database import get_all_latest_live_health, get_all_latest_node_security
    from risk_engine.node_risk import get_all_node_risks

    health_by_node = {item["node_id"]: item for item in get_all_latest_live_health()}
    security_by_node = {item["node_id"]: item for item in get_all_latest_node_security()}
    recommendations = []
    for risk in get_all_node_risks():
        recommendations.extend(generate_node_recommendations(
            risk,
            health_by_node.get(risk["node_id"]),
            security_by_node.get(risk["node_id"]),
        ))
    return recommendations


def generate_recommendation(security_risk_level, failure_risk_level, failure_probability=None, overall_risk_level=None):
    """
    Generates actionable, plain-English recommendation string based on risk levels.
    
    Parameters:
    - security_risk_level (str): 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL'
    - failure_risk_level (str): 'LOW', 'MEDIUM', 'HIGH'
    - failure_probability (float, optional): Optional raw failure probability
    - overall_risk_level (str, optional): Optional integrated risk level
    
    Returns:
    - dict: {"recommendation": str, "action_priority": str, "disclaimer": str}
    """
    sec_level = str(security_risk_level).upper().strip()
    fail_level = str(failure_risk_level).upper().strip()

    # Fallback to probability if failure_risk_level is missing
    if fail_level not in ['LOW', 'MEDIUM', 'HIGH'] and failure_probability is not None:
        p = float(failure_probability)
        if p < 0.30:
            fail_level = 'LOW'
        elif p < 0.70:
            fail_level = 'MEDIUM'
        else:
            fail_level = 'HIGH'

    key = (sec_level, fail_level)

    if key in RECOMMENDATION_RULE_MATRIX:
        rec_text = RECOMMENDATION_RULE_MATRIX[key]
    else:
        # Fallback for unexpected inputs
        if sec_level in ['HIGH', 'CRITICAL'] and fail_level == 'HIGH':
            rec_text = "Critical combined risk. Prioritize machine inspection and cybersecurity investigation."
        elif sec_level in ['HIGH', 'CRITICAL']:
            rec_text = "High cybersecurity risk. Isolate or flag suspicious traffic for administrator review."
        elif fail_level == 'HIGH':
            rec_text = "High failure risk. Schedule preventive maintenance."
        elif fail_level == 'MEDIUM':
            rec_text = "Warning: increased failure risk. Increase monitoring frequency."
        else:
            rec_text = "Machine operating normally. Continue monitoring."

    # Priority rating
    if sec_level == 'CRITICAL' or fail_level == 'HIGH':
        priority = 'URGENT'
    elif sec_level == 'HIGH' or fail_level == 'MEDIUM':
        priority = 'ELEVATED'
    elif sec_level == 'MEDIUM':
        priority = 'MODERATE'
    else:
        priority = 'ROUTINE'

    return {
        "security_risk_level": sec_level,
        "failure_risk_level": fail_level,
        "action_priority": priority,
        "recommendation": rec_text,
        "disclaimer": "These recommendations are generated by the project rule engine for demonstration purposes, not automatic real-world control actions."
    }


if __name__ == "__main__":
    print(generate_recommendation("LOW", "LOW"))
    print(generate_recommendation("HIGH", "LOW"))
    print(generate_recommendation("LOW", "HIGH"))
    print(generate_recommendation("CRITICAL", "HIGH"))
